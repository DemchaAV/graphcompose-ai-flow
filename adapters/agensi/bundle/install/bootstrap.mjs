#!/usr/bin/env node
/**
 * install/bootstrap.mjs — first-run setup of the GraphCompose AI Flow skill
 * bundle, wherever a skill marketplace unpacked it.
 *
 *   node install/bootstrap.mjs --check             report, change nothing
 *   node install/bootstrap.mjs                     finish the install
 *   node install/bootstrap.mjs --install-missing   also install Java, Maven, ImageMagick
 *
 * The bundle ships the TypeScript CLIs as their build output and the preview
 * renderer as Java source; marketplaces refuse prebuilt binaries. What cannot
 * ship in a zip is done here:
 *
 *   1. the toolchain — Java 21+, Maven, ImageMagick — checked, and installed
 *      only when --install-missing says so. They are system packages; the
 *      skill asks the user before passing that flag.
 *   2. the runtime npm dependencies of the three Node tools (pure JS).
 *   3. the preview renderer built from tools/preview-renderer/ with Maven.
 *   4. GraphCompose pulled into the local Maven repository, so the first
 *      render does not stall on a download.
 *   5. the four workflow skills registered with the host that loaded this
 *      bundle — ~/.claude/skills for Claude Code, ~/.codex/skills for Codex —
 *      as stubs pointing back here, so they trigger on their own words.
 *
 * npm, Maven and the platform package manager do the fetching. The one
 * download this script makes itself is Apache Maven's official binary on
 * Windows without Scoop, under --install-missing only, checked against
 * Apache's published SHA-512. Environment variables read: PATH, and
 * CLAUDE_CONFIG_DIR / CODEX_HOME to locate the skills directory.
 *
 * It ends by writing `.bootstrap.json` beside SKILL.md; the skill reads that
 * marker to know setup has run. Re-running is safe: every step checks first.
 */

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import {
  ALWAYS,
  NPM_PACKAGES,
  discoverSkills,
  harnessVersion,
  installRuntimeDeps,
  missingBuilds,
  repoRoot as bundleRoot,
} from "../adapters/lib/runtime.mjs";

const MARKER = path.join(bundleRoot, ".bootstrap.json");
const STUB_PREFIX = "graphcompose-";
const STUB_TAG = "generated by install/bootstrap.mjs";
const RENDERER_DIR = path.join(bundleRoot, "tools", "preview-renderer");
const RENDERER_JAR = "tools/preview-renderer/target/preview-renderer.jar";
const IS_WINDOWS = process.platform === "win32";
const MAVEN_VERSION = "3.9.9";

// --- arguments -----------------------------------------------------------------

function usage(exitCode = 0) {
  process.stdout.write(
    "usage: node install/bootstrap.mjs [options]\n\n" +
      "  --check              report what is missing, change nothing\n" +
      "  --install-missing    install missing Java / Maven / ImageMagick with the\n" +
      "                       platform package manager (winget/scoop, brew, apt)\n" +
      "  --host <claude|codex|none>  which agent to register the workflow skills with\n" +
      "                       (default: detected from where this bundle lives)\n" +
      "  --skills-dir <dir>   register the workflow skills here instead\n" +
      "  --no-stubs           do not register the four workflow skills\n" +
      "  --graphcompose <v>   GraphCompose version to pre-fetch (default: newest pack)\n" +
      "  --skip-deps          do not run npm inside the bundle\n" +
      "  --skip-prefetch      do not pre-fetch GraphCompose into ~/.m2\n" +
      "  --uninstall          remove the registered stubs and the marker\n",
  );
  process.exit(exitCode);
}

function parseArgs(argv) {
  const options = {
    check: false,
    installMissing: false,
    host: null,
    skillsDir: null,
    stubs: true,
    graphcompose: null,
    skipDeps: false,
    skipPrefetch: false,
    uninstall: false,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--help" || arg === "-h") usage(0);
    else if (arg === "--check") options.check = true;
    else if (arg === "--install-missing" || arg === "--yes") options.installMissing = true;
    else if (arg === "--host") options.host = argv[++index];
    else if (arg === "--skills-dir") options.skillsDir = argv[++index];
    else if (arg === "--no-stubs") options.stubs = false;
    else if (arg === "--graphcompose") options.graphcompose = argv[++index];
    else if (arg === "--skip-deps") options.skipDeps = true;
    else if (arg === "--skip-prefetch") options.skipPrefetch = true;
    else if (arg === "--uninstall") options.uninstall = true;
    else {
      process.stderr.write(`[bootstrap] unknown argument: ${arg}\n`);
      usage(2);
    }
  }
  if (options.host && !["claude", "codex", "none"].includes(options.host)) {
    process.stderr.write(`[bootstrap] --host must be claude, codex or none, got ${options.host}\n`);
    process.exit(2);
  }
  return options;
}

// --- output --------------------------------------------------------------------

const ok = (name, detail = "") => console.log(`  ✓ ${name} ${detail}`.trimEnd());
const bad = (name, detail = "") => console.log(`  ✗ ${name} ${detail}`.trimEnd());
const note = (message) => console.log(`    ${message}`);
const head = (title) => console.log(`\n▶ ${title}`);

// --- host ----------------------------------------------------------------------

/** Which agent loaded this bundle, from where the marketplace unpacked it. */
function detectHost(explicit) {
  if (explicit) return explicit;
  const location = bundleRoot.replace(/\\/g, "/").toLowerCase();
  if (location.includes("/.claude/")) return "claude";
  if (location.includes("/.codex/")) return "codex";
  return "none";
}

function skillsDirFor(host) {
  if (host === "claude") {
    return path.join(process.env.CLAUDE_CONFIG_DIR ?? path.join(os.homedir(), ".claude"), "skills");
  }
  if (host === "codex") {
    return path.join(process.env.CODEX_HOME ?? path.join(os.homedir(), ".codex"), "skills");
  }
  return null;
}

// --- toolchain -----------------------------------------------------------------

/** Output of a fixed probe command, or null when it fails. */
function capture(command) {
  // Hard-coded probes only; one command string avoids Node's DEP0190 warning.
  const result = spawnSync(command, { encoding: "utf8", shell: true });
  if (result.error || result.status !== 0) return null;
  return `${result.stdout ?? ""}${result.stderr ?? ""}`;
}

/** Run a fixed command with its output shown; true when it succeeded. */
function runShown(command, cwd = bundleRoot) {
  console.log(`    $ ${command}`);
  const result = spawnSync(command, { stdio: "inherit", shell: true, cwd });
  return !result.error && result.status === 0;
}

const PROBES = {
  java() {
    const match = (capture("java -version") ?? "").match(/version "(\d+)/);
    if (!match) return { found: false, detail: "not found on PATH (need 21+)" };
    const major = Number(match[1]);
    return major >= 21 ? { found: true, detail: `${major}` } : { found: false, detail: `${major} (need 21+)` };
  },
  maven() {
    const match = (capture("mvn -v") ?? "").match(/Apache Maven ([\d.]+)/);
    return match ? { found: true, detail: match[1] } : { found: false, detail: "not found on PATH" };
  },
  imagemagick() {
    const match = (capture("magick -version") ?? "").match(/ImageMagick ([\d.-]+)/);
    return match ? { found: true, detail: match[1] } : { found: false, detail: "`magick` not found on PATH" };
  },
};

const LABEL = { java: "Java", maven: "Maven", imagemagick: "ImageMagick" };

/** The non-interactive install command for a tool here, or null when there is none. */
function installCommand(tool) {
  if (IS_WINDOWS) {
    const winget = (id) =>
      `winget install -e --id ${id} --silent --accept-source-agreements --accept-package-agreements`;
    if (tool === "java") return winget("Microsoft.OpenJDK.21");
    if (tool === "imagemagick") return winget("ImageMagick.ImageMagick");
    // winget carries no Apache Maven package; Scoop's main bucket does, and
    // without Scoop installMavenWindows() takes Apache's own binary.
    return capture("scoop --version") ? "scoop install maven" : null;
  }
  if (process.platform === "darwin") {
    if (tool === "java") return "brew install --cask temurin@21";
    if (tool === "maven") return "brew install maven";
    return "brew install imagemagick";
  }
  const pkg = { java: "openjdk-21-jdk", maven: "maven", imagemagick: "imagemagick" }[tool];
  const isRoot = typeof process.getuid === "function" && process.getuid() === 0;
  return `${isRoot ? "" : "sudo -n "}apt-get install -y ${pkg}`;
}

/** What to tell a person who has to install it themselves. */
function manualHint(tool) {
  if (IS_WINDOWS && tool === "maven") {
    return "scoop install maven   (or re-run with --install-missing to fetch Apache's binary, checksum-verified)";
  }
  const command = installCommand(tool);
  return command ? command.replace("sudo -n ", "sudo ") : null;
}

/** Windows installers update the registry PATH, not this process's. */
function refreshWindowsPath() {
  if (!IS_WINDOWS) return;
  const result = spawnSync(
    "powershell",
    [
      "-NoProfile",
      "-Command",
      "[Environment]::GetEnvironmentVariable('Path','Machine') + ';' + [Environment]::GetEnvironmentVariable('Path','User')",
    ],
    { encoding: "utf8" },
  );
  if (result.status === 0 && result.stdout.trim()) {
    const merged = new Set([...result.stdout.trim().split(";"), ...(process.env.PATH ?? "").split(";")]);
    process.env.PATH = [...merged].filter(Boolean).join(";");
  }
}

/**
 * Maven on Windows without Scoop: the official binary archive from
 * archive.apache.org, accepted only if its SHA-512 matches the checksum
 * Apache publishes beside it. Unpacked under ~/AppData/Local/Programs and
 * added to the user PATH. Runs only under --install-missing, which the skill
 * passes after the user agreed.
 */
async function installMavenWindows() {
  const name = `apache-maven-${MAVEN_VERSION}`;
  const archiveUrl = `https://archive.apache.org/dist/maven/maven-3/${MAVEN_VERSION}/binaries/${name}-bin.zip`;
  const programs = path.join(os.homedir(), "AppData", "Local", "Programs");
  const binDir = path.join(programs, name, "bin");

  if (!fs.existsSync(path.join(binDir, "mvn.cmd"))) {
    console.log(`    downloading ${archiveUrl}`);
    const [archive, checksum] = await Promise.all([fetch(archiveUrl), fetch(`${archiveUrl}.sha512`)]);
    if (!archive.ok || !checksum.ok) {
      bad("Maven", `download failed (${archive.status}/${checksum.status})`);
      return false;
    }
    const bytes = Buffer.from(await archive.arrayBuffer());
    const expected = (await checksum.text()).trim().split(/\s+/)[0].toLowerCase();
    const actual = createHash("sha512").update(bytes).digest("hex");
    if (actual !== expected) {
      bad("Maven", "SHA-512 does not match Apache's published checksum; not unpacking it");
      return false;
    }
    console.log("    SHA-512 matches Apache's published checksum");
    fs.mkdirSync(programs, { recursive: true });
    const zipPath = path.join(os.tmpdir(), `${name}-bin.zip`);
    fs.writeFileSync(zipPath, bytes);
    // bsdtar ships with Windows 10+ and reads zip archives.
    const unpacked = spawnSync("tar", ["-xf", zipPath, "-C", programs], { stdio: "inherit" });
    fs.rmSync(zipPath, { force: true });
    if (unpacked.status !== 0) {
      bad("Maven", "could not unpack the archive");
      return false;
    }
  }

  // Persist for future terminals, and apply to this process.
  const addToUserPath =
    "$userPath=[Environment]::GetEnvironmentVariable('Path','User');" +
    `if (-not ($userPath -split ';' -contains '${binDir}')) {` +
    `[Environment]::SetEnvironmentVariable('Path', ($userPath.TrimEnd(';') + ';${binDir}'), 'User') }`;
  spawnSync("powershell", ["-NoProfile", "-Command", addToUserPath], { stdio: "inherit" });
  process.env.PATH = `${process.env.PATH ?? ""};${binDir}`;
  return true;
}

function probeAll() {
  const missing = [];
  for (const tool of Object.keys(PROBES)) {
    const probe = PROBES[tool]();
    if (probe.found) ok(LABEL[tool], probe.detail);
    else {
      bad(LABEL[tool], probe.detail);
      missing.push(tool);
    }
  }
  return missing;
}

async function ensureToolchain(options) {
  head("Toolchain");
  const nodeMajor = Number(process.versions.node.split(".")[0]);
  if (nodeMajor < 20) {
    bad("Node.js", `v${process.versions.node} (need 20+)`);
    return ["node"];
  }
  ok("Node.js", `v${process.versions.node}`);

  const missing = probeAll();
  if (missing.length === 0 || !options.installMissing || options.check) {
    for (const tool of missing) note(`install: ${manualHint(tool)}`);
    return missing;
  }

  head("Installing missing tools");
  for (const tool of missing) {
    const command = installCommand(tool);
    const installed =
      command !== null ? runShown(command) : IS_WINDOWS && tool === "maven" ? await installMavenWindows() : false;
    if (!installed) note(`${LABEL[tool]} did not install; run it yourself: ${manualHint(tool)}`);
  }
  refreshWindowsPath();

  head("Toolchain after install");
  const stillMissing = probeAll();
  for (const tool of stillMissing) note(`open a new terminal; if still missing: ${manualHint(tool)}`);
  return stillMissing;
}

// --- runtime -------------------------------------------------------------------

function npmDepsMissing() {
  return NPM_PACKAGES.filter((pkg) => !fs.existsSync(path.join(bundleRoot, pkg, "node_modules")));
}

const rendererBuilt = () => fs.existsSync(path.join(bundleRoot, RENDERER_JAR));

/** Build the preview renderer from its shipped sources. */
function buildRenderer() {
  return runShown("mvn -q -B -Dmaven.test.skip=true package", RENDERER_DIR) && rendererBuilt();
}

/**
 * The GraphCompose release the newest knowledge pack was imported from. The
 * directory names only the line (graphcompose-2.4); the patch is recorded in
 * imported-from.json, and guessing ".0" would pre-fetch a superseded release.
 */
function newestPackVersion() {
  const lines = fs
    .readdirSync(path.join(bundleRoot, "skills", "versions"))
    .map((dir) => /^graphcompose-(\d+)\.(\d+)$/.exec(dir))
    .filter(Boolean)
    .sort((left, right) => Number(right[1]) - Number(left[1]) || Number(right[2]) - Number(left[2]));
  if (!lines.length) return null;
  const imported = path.join(bundleRoot, "skills", "versions", lines[0][0], "imported-from.json");
  try {
    const recorded = JSON.parse(fs.readFileSync(imported, "utf8")).graphComposeVersion;
    if (recorded) return recorded;
  } catch {
    /* an older pack without provenance: fall back to the line's first release */
  }
  return `${lines[0][1]}.${lines[0][2]}.0`;
}

function prefetchGraphCompose(version) {
  if (!version) return false;
  const artifact = `io.github.demchaav:graph-compose:${version}`;
  console.log(`    mvn dependency:get ${artifact}`);
  const result = spawnSync(`mvn -q -B dependency:get -Dartifact=${artifact} -Dtransitive=true`, {
    stdio: "pipe",
    shell: true,
    encoding: "utf8",
  });
  return !result.error && result.status === 0;
}

// --- host registration ---------------------------------------------------------

function stubFor(skill, installedName) {
  const canonical = path.join(bundleRoot, "skills", "workflows", skill.dir, "SKILL.md");
  return `---
name: ${installedName}
description: ${skill.description}
---

# ${installedName} (GraphCompose AI Flow)

**Read the canonical skill before doing anything else:**

\`${canonical}\`

That file is the contract — steps, commands, gates and the references it
links to. This stub only lets the agent offer the skill; it is ${STUB_TAG}
and carries no copy of the instructions, so it cannot drift from the source.

Run the commands it gives you from the harness root:

\`${bundleRoot}\`

If \`${MARKER}\` does not exist, setup has not run: follow the "First run"
section of \`${path.join(bundleRoot, "SKILL.md")}\` first.

## Holds regardless

${ALWAYS.map((line) => `- ${line}`).join("\n")}

Every command in the canonical skill is a plain \`node …\` invocation; it
runs unchanged in PowerShell, cmd and bash.
`;
}

/** True for a stub this installer (or the Codex adapter) wrote, or an empty slot. */
function isOurs(dir) {
  const skillFile = path.join(dir, "SKILL.md");
  if (!fs.existsSync(dir)) return true;
  if (!fs.existsSync(skillFile)) return false;
  const text = fs.readFileSync(skillFile, "utf8");
  return text.includes(STUB_TAG) || text.includes("adapters/codex/install.mjs");
}

function registerStubs(dest) {
  const written = [];
  // The bundle may itself sit inside `dest`; never register a stub over it.
  const self = path.resolve(bundleRoot);
  for (const skill of discoverSkills()) {
    const name = `${STUB_PREFIX}${skill.dir}`;
    const dir = path.join(dest, name);
    if (path.resolve(dir) === self) continue;
    if (!isOurs(dir)) {
      note(`skipped ${dir}: a skill not written by this installer is already there`);
      continue;
    }
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "SKILL.md"), stubFor(skill, name));
    written.push(dir);
  }
  return written;
}

function removeStubs(dirs) {
  let removed = 0;
  for (const dir of dirs) {
    if (fs.existsSync(dir) && isOurs(dir)) {
      fs.rmSync(dir, { recursive: true, force: true });
      console.log(`removed ${dir}`);
      removed += 1;
    }
  }
  return removed;
}

// --- main ----------------------------------------------------------------------

const options = parseArgs(process.argv.slice(2));
const version = harnessVersion();
const host = detectHost(options.host);
const skillsDir = options.skillsDir ?? skillsDirFor(host);

if (options.uninstall) {
  const recorded = fs.existsSync(MARKER) ? JSON.parse(fs.readFileSync(MARKER, "utf8")).stubs ?? [] : [];
  const removed = removeStubs(recorded);
  fs.rmSync(MARKER, { force: true });
  console.log(`\n${removed} stub(s) removed. Delete ${bundleRoot} to remove the bundle itself.`);
  process.exit(0);
}

console.log(`GraphCompose AI Flow ${version} — bootstrap`);
console.log(`  bundle : ${bundleRoot}`);
console.log(`  host   : ${host}${skillsDir ? `  (skills: ${skillsDir})` : ""}`);

const missing = await ensureToolchain(options);

head("Harness runtime");
// The renderer ships as source and is built below; anything else missing is a damaged download.
const damaged = missingBuilds().filter((rel) => rel !== RENDERER_JAR);
if (damaged.length) {
  for (const rel of damaged) bad("missing", rel);
  console.log("\nThe bundle is incomplete. Download it again.");
  process.exit(69);
}
ok("prebuilt Node CLIs");

const depsToInstall = npmDepsMissing();
if (depsToInstall.length === 0) ok("npm dependencies");
else if (options.check || options.skipDeps) bad("npm dependencies", `not installed in ${depsToInstall.join(", ")}`);
else {
  const failures = installRuntimeDeps(bundleRoot, (line) => process.stdout.write(`    ${line}`));
  if (failures.length) {
    for (const failure of failures) bad(failure.pkg, failure.error);
    note("npm needs network access; in a sandboxed agent, allow it for this command and re-run.");
  } else ok("npm dependencies");
}

if (rendererBuilt()) ok("preview renderer");
else if (options.check) bad("preview renderer", "not built yet (built from source on install)");
else if (missing.includes("maven") || missing.includes("java")) bad("preview renderer", "needs Java and Maven to build");
else if (buildRenderer()) ok("preview renderer", "built from tools/preview-renderer");
else bad("preview renderer", "Maven build failed; see the output above");

const gcVersion = options.graphcompose ?? newestPackVersion();
let prefetched = false;
if (options.check || options.skipPrefetch) {
  note(`GraphCompose ${gcVersion}: pre-fetch skipped`);
} else if (missing.includes("maven")) {
  note(`GraphCompose ${gcVersion}: pre-fetch needs Maven`);
} else {
  prefetched = prefetchGraphCompose(gcVersion);
  if (prefetched) ok("GraphCompose", `${gcVersion} in the local Maven repository`);
  else note(`GraphCompose ${gcVersion} not pre-fetched (offline?) — Maven fetches it on the first render`);
}

let stubs = [];
head(`Register workflow skills with ${host}`);
if (!options.stubs || !skillsDir) {
  note(skillsDir ? "skipped (--no-stubs)" : "no host detected — pass --host claude or --host codex");
} else if (options.check) {
  note(`would write ${discoverSkills().length} stubs into ${skillsDir}`);
} else {
  stubs = registerStubs(skillsDir);
  for (const dir of stubs) ok(path.basename(dir));
  if (host === "claude" || host === "codex") note("restart the agent session so it picks them up");
}

const remaining = [
  ...missing,
  ...(npmDepsMissing().length ? ["npm-deps"] : []),
  ...(rendererBuilt() ? [] : ["preview-renderer"]),
];
if (options.check) {
  console.log(remaining.length ? `\nMissing: ${remaining.join(", ")}.` : "\nEverything is in place.");
  process.exit(remaining.length ? 1 : 0);
}

fs.writeFileSync(
  MARKER,
  `${JSON.stringify(
    {
      version,
      host,
      skillsDir,
      stubs,
      graphcompose: prefetched ? gcVersion : null,
      missing: remaining,
      at: new Date().toISOString(),
    },
    null,
    2,
  )}\n`,
);

if (remaining.length) {
  console.log(`\nInstalled, but not ready: ${remaining.join(", ")} still missing.`);
  console.log("Re-run with --install-missing, or install them by hand, then run this again.");
  process.exit(1);
}
console.log("\nReady. Give the agent a document reference and ask it to recreate it.");
