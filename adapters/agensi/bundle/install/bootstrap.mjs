#!/usr/bin/env node
/**
 * install/bootstrap.mjs — first-run setup of the GraphCompose AI Flow skill
 * bundle, wherever a skill marketplace unpacked it.
 *
 *   node install/bootstrap.mjs --check             report, change nothing
 *   node install/bootstrap.mjs                     finish the install
 *   node install/bootstrap.mjs --install-missing   also install Java, Maven, ImageMagick
 *
 * The bundle ships prebuilt: the TypeScript CLIs as their build output and
 * the preview renderer as a shaded jar that already carries GraphCompose. What
 * cannot ship in a zip is done here:
 *
 *   1. the toolchain — Java 21+, Maven, ImageMagick — checked, and installed
 *      only when --install-missing says so. They are system packages; the
 *      skill asks the user before passing that flag.
 *   2. the runtime npm dependencies of the three Node tools (pure JS).
 *   3. GraphCompose itself pulled into the local Maven repository, so the
 *      first render does not stall on a download.
 *   4. the four workflow skills registered with the host that loaded this
 *      bundle — ~/.claude/skills for Claude Code, ~/.codex/skills for Codex —
 *      as stubs pointing back here, so they trigger on their own words.
 *
 * It ends by writing `.bootstrap.json` beside SKILL.md; the skill reads that
 * marker to know setup has run. Re-running is safe: every step checks first.
 */

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  ALWAYS,
  NPM_PACKAGES,
  discoverSkills,
  harnessVersion,
  installRuntimeDeps,
  missingBuilds,
  repoRoot as bundleRoot,
} from "../adapters/lib/runtime.mjs";

const MARKER = path.join(bundleRoot, ".bootstrap.json");
const STUB_PREFIX = "graphcompose-";
const STUB_TAG = "generated by install/bootstrap.mjs";
const MAVEN_VERSION = "3.9.9";
const IS_WIN = process.platform === "win32";

// --- arguments -----------------------------------------------------------------

function usage(code = 0) {
  process.stdout.write(
    "usage: node install/bootstrap.mjs [options]\n\n" +
      "  --check              report what is missing, change nothing\n" +
      "  --install-missing    install missing Java / Maven / ImageMagick with the\n" +
      "                       platform package manager (winget/scoop, brew, apt)\n" +
      "  --host <claude|codex|none>  which agent to register the workflow skills with\n" +
      "                       (default: detected from where this bundle lives)\n" +
      "  --skills-dir <dir>   register the workflow skills here instead\n" +
      "  --no-stubs           do not register the four workflow skills\n" +
      "  --graphcompose <v>   GraphCompose version to pre-fetch (default: newest pack)\n" +
      "  --skip-deps          do not run npm inside the bundle\n" +
      "  --skip-prefetch      do not pre-fetch GraphCompose into ~/.m2\n" +
      "  --uninstall          remove the registered stubs and the marker\n",
  );
  process.exit(code);
}

function parseArgs(argv) {
  const out = {
    check: false,
    installMissing: false,
    host: null,
    skillsDir: null,
    stubs: true,
    graphcompose: null,
    skipDeps: false,
    skipPrefetch: false,
    uninstall: false,
  };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === "--help" || a === "-h") usage(0);
    else if (a === "--check") out.check = true;
    else if (a === "--install-missing" || a === "--yes") out.installMissing = true;
    else if (a === "--host") out.host = argv[++i];
    else if (a === "--skills-dir") out.skillsDir = argv[++i];
    else if (a === "--no-stubs") out.stubs = false;
    else if (a === "--graphcompose") out.graphcompose = argv[++i];
    else if (a === "--skip-deps") out.skipDeps = true;
    else if (a === "--skip-prefetch") out.skipPrefetch = true;
    else if (a === "--uninstall") out.uninstall = true;
    else {
      process.stderr.write(`[bootstrap] unknown argument: ${a}\n`);
      usage(2);
    }
  }
  if (out.host && !["claude", "codex", "none"].includes(out.host)) {
    process.stderr.write(`[bootstrap] --host must be claude, codex or none, got ${out.host}\n`);
    process.exit(2);
  }
  return out;
}

// --- output --------------------------------------------------------------------

const color = !process.env.NO_COLOR && process.stdout.isTTY;
const paint = (c, s) => (color ? `\x1b[${c}m${s}\x1b[0m` : s);
const ok = (name, detail = "") => console.log(`  ${paint("32", "✓")} ${name} ${paint("2", detail)}`);
const bad = (name, detail = "") => console.log(`  ${paint("31", "✗")} ${name} ${detail}`);
const note = (s) => console.log(paint("2", `    ${s}`));
const head = (s) => console.log(`\n${paint("1", "▶ " + s)}`);

// --- host ----------------------------------------------------------------------

/**
 * Which agent loaded this bundle. Where the marketplace unpacked it is the
 * strongest signal; the environment is the fallback for a bundle unpacked
 * somewhere neutral and pointed at by hand.
 */
function detectHost(explicit) {
  if (explicit) return explicit;
  const where = bundleRoot.replace(/\\/g, "/").toLowerCase();
  if (where.includes("/.claude/")) return "claude";
  if (where.includes("/.codex/")) return "codex";
  if (process.env.CLAUDECODE || process.env.CLAUDE_CODE_ENTRYPOINT) return "claude";
  if (process.env.CODEX_HOME || process.env.CODEX_SANDBOX || process.env.CODEX_MANAGED_BY_NPM) return "codex";
  return "none";
}

function skillsDirFor(host) {
  if (host === "claude") {
    return path.join(process.env.CLAUDE_CONFIG_DIR ?? path.join(os.homedir(), ".claude"), "skills");
  }
  if (host === "codex") {
    return path.join(process.env.CODEX_HOME ?? path.join(os.homedir(), ".codex"), "skills");
  }
  return null;
}

// --- toolchain -----------------------------------------------------------------

function capture(cmd) {
  // Hard-coded probes only; one command string avoids Node's DEP0190 warning.
  const r = spawnSync(cmd, { encoding: "utf8", shell: true });
  if (r.error || r.status !== 0) return null;
  return `${r.stdout ?? ""}${r.stderr ?? ""}`;
}

function sh(cmd) {
  console.log(paint("2", `    $ ${cmd}`));
  const r = spawnSync(cmd, { stdio: "inherit", shell: true });
  return !r.error && r.status === 0;
}

const PROBES = {
  java() {
    const out = capture("java -version");
    const m = out && out.match(/version "(\d+)/);
    if (!m) return { found: false, detail: "not found on PATH (need 21+)" };
    const major = Number(m[1]);
    return major >= 21 ? { found: true, detail: `${major}` } : { found: false, detail: `${major} (need 21+)` };
  },
  maven() {
    const m = (capture("mvn -v") ?? "").match(/Apache Maven ([\d.]+)/);
    return m ? { found: true, detail: m[1] } : { found: false, detail: "not found on PATH" };
  },
  imagemagick() {
    const m = (capture("magick -version") ?? "").match(/ImageMagick ([\d.-]+)/);
    return m ? { found: true, detail: m[1] } : { found: false, detail: "`magick` not found on PATH" };
  },
};

const LABEL = { java: "Java", maven: "Maven", imagemagick: "ImageMagick" };

/** Non-interactive install commands. `null` means "handled in code". */
function installPlan(tool) {
  if (IS_WIN) {
    const winget = (id) =>
      `winget install -e --id ${id} --silent --accept-source-agreements --accept-package-agreements`;
    if (tool === "java") return winget("Microsoft.OpenJDK.21");
    if (tool === "imagemagick") return winget("ImageMagick.ImageMagick");
    if (tool === "maven") return null; // not on winget: scoop, else the Apache binary
  }
  if (process.platform === "darwin") {
    if (tool === "java") return "brew install --cask temurin@21";
    if (tool === "maven") return "brew install maven";
    if (tool === "imagemagick") return "brew install imagemagick";
  }
  const pkg = { java: "openjdk-21-jdk", maven: "maven", imagemagick: "imagemagick" }[tool];
  const sudo = typeof process.getuid === "function" && process.getuid() === 0 ? "" : "sudo -n ";
  return `${sudo}apt-get install -y ${pkg}`;
}

function manualHint(tool) {
  if (IS_WIN && tool === "maven") return "scoop install maven   (or https://maven.apache.org/download.cgi)";
  const plan = installPlan(tool);
  return plan ? plan.replace("sudo -n ", "sudo ") : null;
}

/** Windows installers update the registry PATH, not this process's. */
function refreshWindowsPath() {
  if (!IS_WIN) return;
  const r = spawnSync(
    "powershell",
    [
      "-NoProfile",
      "-Command",
      "[Environment]::GetEnvironmentVariable('Path','Machine') + ';' + [Environment]::GetEnvironmentVariable('Path','User')",
    ],
    { encoding: "utf8" },
  );
  if (r.status === 0 && r.stdout.trim()) {
    const merged = new Set([...r.stdout.trim().split(";"), ...(process.env.Path ?? "").split(";")]);
    process.env.Path = [...merged].filter(Boolean).join(";");
  }
}

/**
 * Maven on Windows: winget has no package. Scoop when it is there; otherwise
 * the official binary, checked against Apache's published SHA-512, unpacked
 * under %LOCALAPPDATA% and added to the user PATH.
 */
async function installMavenWindows() {
  if (capture("scoop --version")) return sh("scoop install maven");

  const name = `apache-maven-${MAVEN_VERSION}`;
  const url = `https://archive.apache.org/dist/maven/maven-3/${MAVEN_VERSION}/binaries/${name}-bin.zip`;
  const home = path.join(process.env.LOCALAPPDATA ?? path.join(os.homedir(), "AppData", "Local"), "Programs");
  const target = path.join(home, name);
  const bin = path.join(target, "bin");

  if (!fs.existsSync(path.join(bin, "mvn.cmd"))) {
    console.log(paint("2", `    downloading ${url}`));
    const [zip, sum] = await Promise.all([fetch(url), fetch(`${url}.sha512`)]);
    if (!zip.ok || !sum.ok) {
      bad("Maven", `download failed (${zip.status}/${sum.status})`);
      return false;
    }
    const bytes = Buffer.from(await zip.arrayBuffer());
    const expected = (await sum.text()).trim().split(/\s+/)[0].toLowerCase();
    const actual = createHash("sha512").update(bytes).digest("hex");
    if (actual !== expected) {
      bad("Maven", "SHA-512 mismatch — refusing to unpack the download");
      return false;
    }
    fs.mkdirSync(home, { recursive: true });
    const zipPath = path.join(os.tmpdir(), `${name}-bin.zip`);
    fs.writeFileSync(zipPath, bytes);
    // bsdtar ships with Windows 10+ and reads zip archives.
    const unpacked = spawnSync("tar", ["-xf", zipPath, "-C", home], { stdio: "inherit" });
    fs.rmSync(zipPath, { force: true });
    if (unpacked.status !== 0) {
      bad("Maven", "could not unpack the archive");
      return false;
    }
  }

  // Persist for future shells, and apply to this one.
  const script =
    "$p=[Environment]::GetEnvironmentVariable('Path','User');" +
    `if (-not ($p -split ';' -contains '${bin}')) {` +
    `[Environment]::SetEnvironmentVariable('Path', ($p.TrimEnd(';') + ';${bin}'), 'User') }`;
  spawnSync("powershell", ["-NoProfile", "-Command", script], { stdio: "inherit" });
  process.env.Path = `${process.env.Path ?? ""};${bin}`;
  return true;
}

async function ensureToolchain(args) {
  head("Toolchain");
  const node = Number(process.versions.node.split(".")[0]);
  if (node < 20) {
    bad("Node.js", `v${process.versions.node} (need 20+)`);
    return { missing: ["node"] };
  }
  ok("Node.js", `v${process.versions.node}`);

  let missing = [];
  for (const tool of Object.keys(PROBES)) {
    const r = PROBES[tool]();
    if (r.found) ok(LABEL[tool], r.detail);
    else {
      bad(LABEL[tool], r.detail);
      missing.push(tool);
    }
  }
  if (missing.length === 0 || !args.installMissing || args.check) {
    for (const tool of missing) note(`install: ${manualHint(tool)}`);
    return { missing };
  }

  head("Installing missing tools");
  for (const tool of missing) {
    const plan = installPlan(tool);
    const done = plan === null ? await installMavenWindows() : sh(plan);
    if (!done) note(`${LABEL[tool]} did not install; run it yourself: ${manualHint(tool)}`);
  }
  refreshWindowsPath();

  missing = [];
  for (const tool of Object.keys(PROBES)) {
    const r = PROBES[tool]();
    if (r.found) ok(LABEL[tool], r.detail);
    else {
      bad(LABEL[tool], `${r.detail} — open a new terminal; if still missing: ${manualHint(tool)}`);
      missing.push(tool);
    }
  }
  return { missing };
}

// --- runtime -------------------------------------------------------------------

function npmDepsMissing() {
  return NPM_PACKAGES.filter((pkg) => !fs.existsSync(path.join(bundleRoot, pkg, "node_modules")));
}

/** The GraphCompose version of the newest knowledge pack this bundle carries. */
function newestPackVersion() {
  const dirs = fs
    .readdirSync(path.join(bundleRoot, "skills", "versions"))
    .map((d) => /^graphcompose-(\d+)\.(\d+)$/.exec(d))
    .filter(Boolean)
    .sort((a, b) => Number(b[1]) - Number(a[1]) || Number(b[2]) - Number(a[2]));
  return dirs.length ? `${dirs[0][1]}.${dirs[0][2]}.0` : null;
}

function prefetchGraphCompose(version) {
  if (!version) return false;
  const artifact = `io.github.demchaav:graph-compose:${version}`;
  console.log(paint("2", `    mvn dependency:get ${artifact}`));
  const r = spawnSync(`mvn -q -B dependency:get -Dartifact=${artifact} -Dtransitive=true`, {
    stdio: "pipe",
    shell: true,
    encoding: "utf8",
  });
  return !r.error && r.status === 0;
}

// --- host registration ---------------------------------------------------------

function stubFor(skill, installedName) {
  const canonical = path.join(bundleRoot, "skills", "workflows", skill.dir, "SKILL.md");
  return `---
name: ${installedName}
description: ${skill.description}
---

# ${installedName} (GraphCompose AI Flow)

**Read the canonical skill before doing anything else:**

\`${canonical}\`

That file is the contract — steps, commands, gates and the references it
links to. This stub only lets the agent offer the skill; it is ${STUB_TAG}
and carries no copy of the instructions, so it cannot drift from the source.

Run the commands it gives you from the harness root:

\`${bundleRoot}\`

If \`${MARKER}\` does not exist, setup has not run: follow the "First run"
section of \`${path.join(bundleRoot, "SKILL.md")}\` first.

## Holds regardless

${ALWAYS.map((line) => `- ${line}`).join("\n")}

Every command in the canonical skill is a plain \`node …\` invocation; it
runs unchanged in PowerShell, cmd and bash.
`;
}

/** Our stub, or a directory we must not overwrite. */
function isOurs(dir) {
  const file = path.join(dir, "SKILL.md");
  if (!fs.existsSync(dir)) return true;
  if (!fs.existsSync(file)) return false;
  const text = fs.readFileSync(file, "utf8");
  return text.includes(STUB_TAG) || text.includes("adapters/codex/install.mjs");
}

function registerStubs(dest) {
  const written = [];
  // The bundle may itself sit inside `dest`; never register a stub over it.
  const self = path.resolve(bundleRoot);
  for (const skill of discoverSkills()) {
    const name = `${STUB_PREFIX}${skill.dir}`;
    const dir = path.join(dest, name);
    if (path.resolve(dir) === self) continue;
    if (!isOurs(dir)) {
      note(`skipped ${dir}: a skill not written by this installer is already there`);
      continue;
    }
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "SKILL.md"), stubFor(skill, name));
    written.push(dir);
  }
  return written;
}

function removeStubs(dirs) {
  let removed = 0;
  for (const dir of dirs) {
    if (fs.existsSync(dir) && isOurs(dir)) {
      fs.rmSync(dir, { recursive: true, force: true });
      console.log(`removed ${dir}`);
      removed += 1;
    }
  }
  return removed;
}

// --- main ----------------------------------------------------------------------

const args = parseArgs(process.argv.slice(2));
const version = harnessVersion();
const host = detectHost(args.host);
const skillsDir = args.skillsDir ?? skillsDirFor(host);

if (args.uninstall) {
  const recorded = fs.existsSync(MARKER) ? JSON.parse(fs.readFileSync(MARKER, "utf8")).stubs ?? [] : [];
  const removed = removeStubs(recorded);
  fs.rmSync(MARKER, { force: true });
  console.log(`\n${removed} stub(s) removed. Delete ${bundleRoot} to remove the bundle itself.`);
  process.exit(0);
}

console.log(`GraphCompose AI Flow ${version} — bootstrap`);
console.log(paint("2", `  bundle : ${bundleRoot}`));
console.log(paint("2", `  host   : ${host}${skillsDir ? `  (skills: ${skillsDir})` : ""}`));

const { missing } = await ensureToolchain(args);

head("Harness runtime");
const unbuilt = missingBuilds();
if (unbuilt.length) {
  // The bundle is built before it is zipped; this is a damaged download.
  for (const rel of unbuilt) bad("missing", rel);
  console.log("\nThe bundle is incomplete. Download it again.");
  process.exit(69);
}
ok("prebuilt CLIs and preview renderer");

const depsToInstall = npmDepsMissing();
if (depsToInstall.length === 0) ok("npm dependencies");
else if (args.check || args.skipDeps) bad("npm dependencies", `not installed in ${depsToInstall.join(", ")}`);
else {
  const failures = installRuntimeDeps(bundleRoot, (line) => process.stdout.write(`    ${line}`));
  if (failures.length) {
    for (const f of failures) bad(f.pkg, f.error);
    note("npm needs network access; in a sandboxed agent, allow it for this command and re-run.");
  }
}

const gcVersion = args.graphcompose ?? newestPackVersion();
let prefetched = false;
if (args.check || args.skipPrefetch) {
  note(`GraphCompose ${gcVersion}: pre-fetch skipped`);
} else if (missing.includes("maven")) {
  note(`GraphCompose ${gcVersion}: pre-fetch needs Maven`);
} else {
  prefetched = prefetchGraphCompose(gcVersion);
  prefetched
    ? ok("GraphCompose", `${gcVersion} in the local Maven repository`)
    : note(`GraphCompose ${gcVersion} not pre-fetched (offline?) — Maven fetches it on the first render`);
}

let stubs = [];
head(`Register workflow skills with ${host}`);
if (!args.stubs || !skillsDir) {
  note(skillsDir ? "skipped (--no-stubs)" : "no host detected — pass --host claude or --host codex");
} else if (args.check) {
  note(`would write ${discoverSkills().length} stubs into ${skillsDir}`);
} else {
  stubs = registerStubs(skillsDir);
  for (const dir of stubs) ok(path.basename(dir));
  if (host === "claude" || host === "codex") note("restart the agent session so it picks them up");
}

const remaining = [...missing, ...(npmDepsMissing().length ? ["npm-deps"] : [])];
if (args.check) {
  console.log(remaining.length ? `\nMissing: ${remaining.join(", ")}.` : "\nEverything is in place.");
  process.exit(remaining.length ? 1 : 0);
}

fs.writeFileSync(
  MARKER,
  `${JSON.stringify(
    {
      version,
      host,
      skillsDir,
      stubs,
      graphcompose: prefetched ? gcVersion : null,
      missing: remaining,
      at: new Date().toISOString(),
    },
    null,
    2,
  )}\n`,
);

if (remaining.length) {
  console.log(`\n${paint("33", "Installed, but not ready:")} ${remaining.join(", ")} still missing.`);
  console.log("Re-run with --install-missing, or install them by hand, then run this again.");
  process.exit(1);
}
console.log(`\n${paint("32", "Ready.")} Give the agent a document reference and ask it to recreate it.`);
